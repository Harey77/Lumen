test('note form validates, saves only after the write, and delete is confirmed', async ({ page }) => {
  await page.goto('/library')
  await page.getByRole('button', { name: 'Save note' }).click()
  const title = page.getByLabel('Title')
  await expect(title).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByText('Give the note a title.')).toBeVisible()
  await expect(title).toBeFocused()
  await title.fill('Proton gradient')
  await page.getByRole('button', { name: 'Save note' }).click()
  await expect(page.getByText('Write something in the note.')).toBeVisible()
  await expect(title).toHaveValue('Proton gradient')
  await page.getByLabel('Note', { exact: true }).fill('Stored like water behind a dam.')
  await page.getByRole('button', { name: 'Save note' }).click()
  await expect(page.getByText('Note saved on this device.')).toBeVisible()
  await expect(page.locator('.note__title')).toHaveText(['Proton gradient'])

  // Persisted in IndexedDB.
  await page.reload()
  await expect(page.locator('.note__title')).toHaveText(['Proton gradient'])

  const del = page.getByRole('button', { name: 'Delete note: Proton gradient' })
  await del.click()
  const dialog = page.getByRole('dialog', { name: 'Delete this note?' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Cancel' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(del).toBeFocused()
  await del.click()
  await dialog.getByRole('button', { name: 'Delete note' }).click()
  await expect(page.locator('.note')).toHaveCount(0)
  await expect(page.getByText('No notes yet.')).toBeVisible()
})

