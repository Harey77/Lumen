test('scroll progress and back to top on a long page', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 600 })
  await page.goto('/settings')
  // Hidden from assistive tech until it appears, so locate it by class first.
  const top = page.locator('.back-to-top')
  await expect(top).toHaveAttribute('data-visible', 'false')
  await page.evaluate(() => scrollTo(0, document.documentElement.scrollHeight))
  await expect(top).toHaveAttribute('data-visible', 'true')
  await top.click()
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(0)

  await page.goto('/perspectives')
  // Wait for the saved-answers read, which changes the page height (the bar must follow it).
  await expect(page.getByRole('button', { name: 'Save my argument' })).toBeVisible()
  await page.evaluate(() => scrollTo(0, document.documentElement.scrollHeight))
  await expect.poll(() => page.getByTestId('scroll-progress').evaluate((el) => el.style.transform)).toBe('scaleX(1)')
})

